const logoCandidates = [
  "images/mismar-logo.png",
  "assets/mismar-logo.png",
  "images/mismar-logo.svg",
  "assets/mismar-logo.svg",
  "assets/logo.svg",
  "assets/logo.png",
];

const topBar = document.querySelector(".top-bar");
const languageButtons = document.querySelectorAll("[data-lang]");
const translatableElements = document.querySelectorAll("[data-i18n]");
const slides = document.querySelectorAll(".hero-slide");
const dots = document.querySelectorAll(".slider-dot");
const nextButton = document.querySelector("[data-slider-next]");
const prevButton = document.querySelector("[data-slider-prev]");
const logos = document.querySelectorAll("[data-logo], [data-footer-logo]");
const pageImages = document.querySelectorAll("img:not([data-logo]):not([data-footer-logo])");

let activeSlide = 0;
let slideTimer;

function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.ar;

  document.documentElement.lang = dictionary.lang;
  document.documentElement.dir = dictionary.dir;
  document.body.dir = dictionary.dir;
  document.title = dictionary.title;

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === lang);
  });

  localStorage.setItem("beit-altuhafiat-language", lang);
}

function showSlide(index) {
  activeSlide = (index + slides.length) % slides.length;

  slides.forEach((slide, slideIndex) => {
    slide.classList.toggle("is-active", slideIndex === activeSlide);
  });

  dots.forEach((dot, dotIndex) => {
    dot.classList.toggle("is-active", dotIndex === activeSlide);
  });
}

function restartSlider() {
  window.clearInterval(slideTimer);
  slideTimer = window.setInterval(() => showSlide(activeSlide + 1), 6400);
}

function updateTopBar() {
  topBar.classList.toggle("is-scrolled", window.scrollY > 18);
}

function handleImageFailure(image) {
  if (image.dataset.fallback && image.src.indexOf(image.dataset.fallback) === -1) {
    image.src = image.dataset.fallback;
    return;
  }

  image.classList.add("is-missing");
  image.setAttribute("aria-hidden", "true");
}

function attachFallbacks() {
  pageImages.forEach((image) => {
    image.addEventListener("error", () => handleImageFailure(image));

    if (image.complete && image.naturalWidth === 0) {
      handleImageFailure(image);
    }
  });
}

function tryLogo(logo, index = 0) {
  if (index >= logoCandidates.length) {
    logo.classList.add("is-missing");
    return;
  }

  logo.addEventListener(
    "error",
    () => {
      tryLogo(logo, index + 1);
    },
    { once: true }
  );

  logo.src = logoCandidates[index];

  window.setTimeout(() => {
    if (logo.complete && logo.naturalWidth === 0 && !logo.classList.contains("is-missing")) {
      tryLogo(logo, index + 1);
    }
  }, 0);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

dots.forEach((dot) => {
  dot.addEventListener("click", () => {
    showSlide(Number(dot.dataset.slideTo));
    restartSlider();
  });
});

nextButton.addEventListener("click", () => {
  showSlide(activeSlide + 1);
  restartSlider();
});

prevButton.addEventListener("click", () => {
  showSlide(activeSlide - 1);
  restartSlider();
});

window.addEventListener("scroll", updateTopBar, { passive: true });

attachFallbacks();
logos.forEach((logo) => tryLogo(logo));
applyLanguage(localStorage.getItem("beit-altuhafiat-language") || "ar");
showSlide(0);
restartSlider();
updateTopBar();

